"""Solve one context and summarize a partition."""

from __future__ import annotations

from time import perf_counter

import numpy as np
import pandas as pd
from scipy.stats import chi2, spearmanr
from sklearn.metrics import adjusted_rand_score

from .candidates import exact_columns, exact_geometric_columns, geometry_combinations
from .gates import group_audit, original_pairs, pair_edit_cost, source_labels
from .ordered import best_ordered
from .partition import Partition, exact_oracle, solve_master


def candidate_family(data, policy):
    """Complete admissible family and its scope, or ``(None, None)`` if too large."""
    if len(data) <= policy.exact_n:
        return exact_columns(data, policy), "complete_subset_space"
    if geometry_combinations(data, policy) <= policy.max_exact_geometry_combinations:
        return exact_geometric_columns(data, policy), "complete_geometric_space"
    return None, None


def solve_context(data, policy, mode="compact", extra_orders=0):
    """Solve one context with EVCC-A and with the ordered comparator.

    Returns ``(results, columns)``. ``results`` maps ``"evcca"``, ``"ordered"``
    and, for contexts small enough for subset enumeration, ``"oracle"`` to a
    :class:`Partition`. When the complete family exceeds the enumeration
    budget, EVCC-A is solved over the groups generated by the tested orders
    and the result is not marked optimal.
    """
    data = data.reset_index(drop=True)
    started = perf_counter()
    n = len(data)
    whole = group_audit(data, np.arange(n), policy)
    if mode == "compact" and whole["compliant"]:
        objective = (0, 1, whole["cost"])
        columns = {(1 << n) - 1: whole["cost"]}
        result = {
            name: Partition(
                np.zeros(n, int), objective, "optimal", "global_one_group_bound", True, perf_counter() - started, 1
            )
            for name in ("ordered", "evcca")
        }
        if n <= policy.exact_n:
            result["oracle"] = Partition(
                np.zeros(n, int), objective, "optimal", "independent_global_one_group_bound", True, 0, 1
            )
        if extra_orders:
            result["ordered_directions"] = result["ordered"]
        return result, columns

    exact, scope = candidate_family(data, policy)
    ordered, pool = best_ordered(data, policy, exact, mode)
    complete = exact is not None
    columns = exact if complete else pool
    scope = scope if complete else "ordered_candidate_pool"
    evcca = solve_master(data, policy, columns, mode, scope, witness=ordered)
    evcca.optimal = evcca.optimal and complete
    worse = evcca.objective[:-1] > ordered.objective[:-1] or (
        evcca.objective[:-1] == ordered.objective[:-1] and evcca.objective[-1] > ordered.objective[-1] + 1e-9
    )
    if evcca.status == "solver_no_incumbent" or worse:
        evcca = Partition(
            ordered.labels.copy(),
            ordered.objective,
            "feasible_ordered_fallback",
            scope,
            False,
            evcca.seconds,
            len(columns),
        )
    evcca.seconds = perf_counter() - started - ordered.seconds
    result = {"ordered": ordered, "evcca": evcca}
    if scope == "complete_subset_space":
        result["oracle"] = exact_oracle(data, policy, exact, mode)
    if extra_orders:
        result["ordered_directions"], _ = best_ordered(data, policy, exact, mode, random_count=extra_orders)
    return result, columns


def summarize(data, partition, policy):
    """Context-level summary row and a per-group table for ``partition``."""
    labels = partition.labels
    n = len(data)
    rows = []
    for label in sorted(set(labels) - {-1}):
        members = np.flatnonzero(labels == label)
        audit = group_audit(data, members, policy)
        row = {
            "group": label,
            "n": len(members),
            "boreholes": data.iloc[members].borehole_id.nunique(),
            "depth_min": data.iloc[members].depth_m.min(),
            "depth_max": data.iloc[members].depth_m.max(),
            "contiguous": audit["contiguous"],
            "compliant": audit["compliant"],
            "nu_critical": audit["nu_critical"],
        }
        for j, name in enumerate(policy.properties):
            row[name + "_cv"] = audit["cv"][j]
            row[name + "_nu"] = audit["nu"][j]
            # Normal-theory upper bound of the CV; descriptive only.
            row[name + "_cv_upper_sd_approx"] = audit["cv"][j] * np.sqrt(
                (len(members) - 1) / chi2.ppf(0.05, len(members) - 1)
            )
            depths = data.iloc[members].depth_m.to_numpy()
            measured = data.iloc[members][name].to_numpy()
            if np.ptp(depths) > 0 and np.ptp(measured) > 0:
                r, p_value = spearmanr(depths, measured)
            else:
                r, p_value = np.nan, np.nan
            row[name + "_depth_spearman"] = r
            row[name + "_depth_p"] = p_value
        rows.append(row)

    groups = pd.DataFrame(rows)
    a = int((labels < 0).sum())
    k = len(rows)
    groups_present = set(labels) - {-1}
    pair_edits = original_pairs(data) + sum(pair_edit_cost(data, np.flatnonzero(labels == g)) for g in groups_present)
    budget = policy.budget(n)
    strict = k > 0 and groups.compliant.all() and a <= budget
    initial = data.initial_ige if "initial_ige" in data else pd.Series(source_labels(data))
    summary = {
        "n": n,
        "A": a,
        "K": k,
        "review_budget": budget,
        "budget_excess": max(0, a - budget),
        "assigned_n": n - a,
        "strict_feasible": bool(strict),
        "strict_accepted_n": n - a if strict else 0,
        "D": pair_edits,
        "status": partition.status,
        "scope": partition.scope,
        "optimal": partition.optimal,
        "seconds": partition.seconds,
        "candidate_count": partition.candidate_count,
        "order": partition.order,
        "mip_gap": partition.mip_gap,
        "initial_groups": initial.nunique(),
        "initial_ari": adjusted_rand_score(initial, labels),
        "B": sum(group_audit(data, np.flatnonzero(labels == g), policy)["cost"] for g in groups_present),
    }
    return summary, groups
